#!/usr/bin/env python3
"""Generate crates/nxb-split/src/sjis/table.rs from Python's `shift_jis` codec (the codec the reference split decodes
BND3 names with: `bytes.decode('shift-jis', 'replace')`).
Usage: gen_sjis_table.py <out file>   (dev tool, output is committed)

The table is indexed by the row and column of a two-byte character as the codec computes them from the two bytes
(94 rows of 94 columns), 0 where the codec has no character."""
import sys

rows = [[0] * 94 for _ in range(94)]
for s1 in list(range(0x81, 0xa0)) + list(range(0xe0, 0xfd)):
    for s2 in list(range(0x40, 0x7f)) + list(range(0x80, 0xfd)):
        ch = bytes([s1, s2]).decode('shift_jis', 'replace')
        if len(ch) != 1 or ch == '\ufffd':
            continue
        c1 = s1 - 0x81 if s1 < 0xe0 else s1 - 0xc1
        c2 = s2 - 0x40 if s2 < 0x80 else s2 - 0x41
        rows[2 * c1 + (c2 >= 0x5e)][c2 if c2 < 0x5e else c2 - 0x5e] = ord(ch)

with open(sys.argv[1], 'w') as f:
    f.write('//! The JIS X 0208 characters of Python\'s `shift_jis` codec (generated by `tools/gen_sjis_table.py`, do not edit).\n')
    f.write('//! Row and column follow the arithmetic of `sjis::decode`. 0 is no character.\n\n')
    f.write('#[rustfmt::skip]\n')
    f.write('pub(super) static JIS0208: [[u16; 94]; 94] = [\n')
    for cells in rows:
        f.write('    [' + ', '.join('0x%04x' % v for v in cells) + '],\n')
    f.write('];\n')
