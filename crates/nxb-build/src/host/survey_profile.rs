/// `ipa_name(name, app)`.
pub fn ipa_name(name: &str, app: u64) -> String {
    let cleaned = name.replace(['\'', '\u{2019}'], "");
    let mut words = Vec::new();
    let mut cur = String::new();
    for c in cleaned.chars().chain(std::iter::once('\0')) {
        if c.is_ascii_alphanumeric() {
            cur.push(c);
        } else if !cur.is_empty() {
            words.push(std::mem::take(&mut cur));
        }
    }
    let mut out = String::new();
    for w in words {
        let upper =
            w.chars().any(|c| c.is_ascii_uppercase()) && !w.chars().any(|c| c.is_ascii_lowercase());
        if upper && w.len() > 1 {
            out.push_str(&w[..1]);
            out.push_str(&w[1..].to_lowercase());
        } else {
            out.push_str(&w[..1].to_uppercase());
            out.push_str(&w[1..]);
        }
    }
    let out: String = out.chars().take(48).collect();
    format!(
        "{}.ipa",
        if out.is_empty() {
            format!("{app:016X}")
        } else {
            out
        }
    )
}

/// `write_profile`'s `game.tsv`: the provisional profile of a survey. `survey_path` is the report's path (written in
/// the second comment line).
pub fn provisional_game_tsv(s: &Survey, app: u64, survey_path: &str) -> TsvFile {
    let (f, g): (&Facts, &Guess) = (&s.facts, &s.guess);
    let r = &f.romfs;
    let mut groups: Vec<String> = Vec::new();
    let mut seen: Vec<String> = vec!["main".into(), "other".into()];
    for (d, _) in r.dirs.most_common(24) {
        let mut n: String = d
            .to_lowercase()
            .chars()
            .filter(|c| matches!(c, 'a'..='z' | '0'..='9'))
            .take(16)
            .collect();
        if n.is_empty() {
            n = "g".into();
        }
        while seen.contains(&n) {
            n.push('x');
        }
        seen.push(n.clone());
        groups.push(format!("/{d}/={n}"));
    }
    let mut store: Vec<String> = r
        .extb
        .iter()
        .filter(|(e, b)| {
            let n = r.exts.get(e);
            !e.is_empty() && n != 0 && (*b as f64 / n as f64 >= 1048576.0 || 2 * r.extc.get(e) >= n)
        })
        .map(|(e, _)| e.to_string())
        .collect();
    store.sort();
    store.push(".metallib".into());
    let name = if s.name.is_empty() {
        format!("{app:016X}")
    } else {
        s.name.clone()
    };
    let mods: Vec<&str> = g
        .value("modules")
        .unwrap_or("")
        .split_whitespace()
        .collect();
    let mut t = TsvFile::new();
    let key = |t: &mut TsvFile, k: &str, default: Option<&str>| {
        let (v, why) = match g.get(k) {
            Some((v, w)) => (Some(v.as_str()), w.as_str()),
            None => (default, ""),
        };
        if let Some(v) = v {
            if !why.is_empty() {
                t.push_comment(why);
            }
            t.push_row(k, &[v]);
        }
    };
    t.push_comment("Provisional game profile (generated by scripts/build_ipa_from_nsp.py from the survey with dm/games/profile_guess.py, not checked by hand)");
    t.push_comment(&format!(
        "{name}, SDK {}, survey {survey_path}",
        if f.sdk == 0 {
            "?".to_string()
        } else {
            f.sdk.to_string()
        }
    ));
    t.push_blank();
    t.push_comment("---- Identity ----");
    t.push_row("title_id", &[&format!("{app:016X}")]);
    t.push_row(
        "program_id",
        &[&format!(
            "{:016X}",
            f.program.filter(|p| *p != 0).unwrap_or(app)
        )],
    );
    t.push_blank();
    t.push_comment("---- App ----");
    t.push_row("name", &[&name]);
    t.push_row("ipa", &[&ipa_name(&name, app)]);
    t.push_row("app_category", &["public.app-category.games"]);
    key(&mut t, "pad_layout", None);
    key(&mut t, "op_mode", None);
    t.push_blank();
    t.push_comment("---- Versions ----");
    let bids: Vec<String> = mods
        .iter()
        .map(|m| format!("{m}={}", f.module(m).map_or("", |x| x.bid.as_str())))
        .collect();
    let mut b: Vec<&str> = vec![&s.version, &s.display];
    b.extend(bids.iter().map(String::as_str));
    t.push_row("build", &b);
    t.push_row("package", &[&s.version]);
    t.push_row("shader_versions", &[&s.version]);
    t.push_blank();
    t.push_comment("---- Files ----");
    key(&mut t, "modules", None);
    t.push_row("romfs_marker", &[&r.biggest.1]);
    t.push_row("zip_store", &[&store.join(":")]);
    t.push_blank();
    t.push_comment("---- Memory ----");
    for k in [
        "mem_reserve",
        "mem_alias",
        "mem_stack",
        "app_pool",
        "sys_resource",
    ] {
        key(&mut t, k, None);
    }
    t.push_blank();
    t.push_comment("---- Shader split ----");
    let gd = if groups.is_empty() {
        "/=romfs".to_string()
    } else {
        groups.join(" ")
    };
    key(&mut t, "shader_groups", Some(&gd));
    t.push_row("shader_note", &[&format!("{name} shaders")]);
    t
}

/// `write_profile(pdir, app, f)`: `game.tsv` and the empty tables into `pdir`. An existing `game.tsv` is kept
/// (`Ok(false)`: nothing written).
pub fn write_profile(pdir: &Path, app: u64, s: &Survey, survey_path: &str) -> Result<bool, String> {
    std::fs::create_dir_all(pdir).map_err(|e| format!("{}: {e}", pdir.display()))?;
    if pdir.join("game.tsv").exists() {
        return Ok(false);
    }
    provisional_game_tsv(s, app, survey_path)
        .save(&pdir.join("game.tsv"))
        .map_err(|e| e.to_string())?;
    for (n, text) in EMPTY_TABLES {
        std::fs::write(pdir.join(n), text).map_err(|e| format!("{n}: {e}"))?;
    }
    Ok(true)
}

/// `set_keys`: writes keys into a provisional `game.tsv` under their reasons in a section of their own at the end.
/// Earlier rows of the keys (and the reason line right above one) go. A key whose value is `None` only goes.
pub fn set_keys(
    text: &str,
    changes: &[(String, Option<(String, String)>)],
    section: &str,
) -> String {
    let mut out: Vec<String> = Vec::new();
    for line in super::pyfmt::splitlines(text) {
        let k = line.split('\t').next().unwrap_or("");
        if changes.iter().any(|c| c.0 == k) {
            if out
                .last()
                .is_some_and(|l| l.starts_with("# ") && !l.starts_with("# ----"))
            {
                out.pop();
            }
            continue;
        }
        out.push(line.to_string());
    }
    let put: Vec<_> = changes
        .iter()
        .filter_map(|(k, v)| v.as_ref().map(|v| (k, v)))
        .collect();
    if !put.is_empty() {
        out.push(String::new());
        out.push(format!("# ---- {section} ----"));
        for (k, (v, why)) in put {
            if !why.is_empty() {
                out.push(format!("# {why}"));
            }
            out.push(format!("{k}\t{v}"));
        }
    }
    format!("{}\n", out.join("\n"))
}

fn signals_to_changes(s: &Signals) -> Vec<(String, Option<(String, String)>)> {
    s.iter()
        .map(|(k, v)| (k.clone(), Some(v.clone())))
        .collect()
}

/// The keys of a `game.tsv` as `game.py` gives them (the first row of each key).
pub fn keys_of(text: &str) -> Keys {
    let t = TsvFile::parse(text);
    let mut k = Keys::new();
    for r in t.rows() {
        k.entry(r.key.clone()).or_insert_with(|| r.joined());
    }
    k
}

/// `refine_after_rewrite` for a provisional profile: the new text when `mem_used` changes. `modules` are the profile's
/// modules the folder `patched` holds. Explicit values win: a `mem_used` that is not the computed one stays.
pub fn refine_after_rewrite(
    text: &str,
    has_va: bool,
    patched: &Path,
) -> Result<Option<String>, String> {
    let (mut section, mut reason) = (String::new(), String::new());
    for line in super::pyfmt::splitlines(text) {
        if line.starts_with("# ----") {
            section = line.to_string();
        }
        if line.split('\t').next().unwrap_or("").trim() == "mem_used" {
            let computed = section == "# ---- After the rewrite ----"
                && [
                    "# used memory for the rewritten modules",
                    "# used memory for the current rewritten modules",
                    "# the rewritten modules are larger than the default 64 MB",
                ]
                .iter()
                .any(|p| reason.starts_with(p));
            if !computed {
                return Ok(None);
            }
        }
        reason = line.to_string();
    }
    if has_va {
        return Ok(None);
    }
    let keys = keys_of(text);
    let modules: Vec<String> = keys
        .get("modules")
        .map_or("main", String::as_str)
        .split_whitespace()
        .filter(|m| patched.join(m).is_file() || patched.join(format!("{m}.patched.bin")).is_file())
        .map(str::to_string)
        .collect();
    let used = mem_used(patched, &modules)?.unwrap_or(0x400_0000);
    let cur = keys
        .get("mem_used")
        .map_or(Ok(0x400_0000), |v| super::pyfmt::int0(v).map(|x| x as u64))?;
    if cur == used {
        return Ok(None);
    }
    Ok(Some(set_keys(
        text,
        &[(
            "mem_used".into(),
            Some((
                format!("{used:#x}"),
                "used memory for the current rewritten modules, at least the default 64 MB".into(),
            )),
        )],
        "After the rewrite",
    )))
}

/// `heap_check_needed(exefs)`: virtual address memory and a heap.
pub fn heap_check_needed(exefs: &Path) -> Result<bool, String> {
    let (img, ..) = super::guess::read_nso(&exefs.join("main"))?;
    let imports: Vec<String> = super::nsofacts::dynsyms(&img)?
        .into_iter()
        .filter(|s| !s.1)
        .map(|s| s.0)
        .collect();
    Ok(super::guess::npdm(&exefs.join("main.npdm"))?.0 != 0
        && imports.iter().any(|s| s == super::guess::HEAP_API))
}

/// `has_va(exefs)`: the NPDM declares system resource (the game takes its memory as address regions).
pub fn has_va(exefs: &Path) -> Result<bool, String> {
    Ok(super::guess::npdm(&exefs.join("main.npdm"))?.0 != 0)
}

/// `heap_checked(g)`: the profile carries the heap check's stamp.
pub fn heap_checked(text: &str) -> bool {
    super::pyfmt::splitlines(text)
        .iter()
        .any(|l| l.starts_with("# heap check: "))
}

/// `region_checked(g, patched)`: the stamp of a check of this rewrite (`rewrite` is its short key).
pub fn region_checked(text: &str, rewrite: &str) -> bool {
    let end = format!("(rewrite {rewrite})");
    super::pyfmt::splitlines(text)
        .iter()
        .any(|l| l.starts_with("# address regions: ") && l.ends_with(&end))
}

/// What a heap check made of a host log.
#[derive(Clone, Debug)]
pub struct HeapCheck {
    /// The profile text with the keys and the stamp.
    pub text: String,
    /// The keys that were set.
    pub set: Signals,
    /// How the boot ended (the stamp's words).
    pub how: String,
}

/// The part of `heap_check` after the boot: the keys the log shows go into the profile, which is stamped with `date`.
/// `rc` is the host's exit code when it stopped by itself.
pub fn heap_check_result(
    text: &str,
    log: &str,
    rc: Option<i32>,
    date: &str,
) -> Result<HeapCheck, String> {
    let g = keys_of(text);
    let mut sig: Signals = heap_signals(log, &g)?
        .into_iter()
        .filter(|(k, v)| g.get(k).map_or("", String::as_str) != v.0)
        .collect();
    for (k, v) in depth_signal(log, &g) {
        match sig.iter_mut().find(|s| s.0 == k) {
            Some(s) => s.1 = v,
            None => sig.push((k, v)),
        }
    }
    let m = log.find("[mem] heap ").and_then(|i| {
        let r = &log[i + 11..];
        let n = r
            .bytes()
            .take_while(|c| c.is_ascii_digit() || *c == b'.')
            .count();
        (n > 0 && r[n..].starts_with(" GB")).then(|| format!("heap {}", &r[..n + 3]))
    });
    let how = if log.contains("SetHeapSize OOM") {
        "the heap request did not fit".to_string()
    } else if let Some(m) = m {
        m
    } else if log.contains(">>> nnMain") {
        "no heap set".to_string()
    } else if let Some(rc) = rc {
        format!("the host stopped before nnMain (exit {rc})")
    } else {
        "no nnMain within the time limit".to_string()
    };
    let mut out = if sig.is_empty() {
        text.to_string()
    } else {
        set_keys(text, &signals_to_changes(&sig), "Heap check on the Mac")
    };
    out.push_str(&format!("\n# heap check: {date}, {how}"));
    if !sig.is_empty() {
        out.push_str(&format!(
            "; set {}",
            sig.iter()
                .map(|s| s.0.as_str())
                .collect::<Vec<_>>()
                .join(", ")
        ));
    }
    out.push('\n');
    Ok(HeapCheck {
        text: out,
        set: sig,
        how,
    })
}

/// The reason line of a `stdalloc_cap` the region check set.
pub const CHECKED_CAP: &str = "from the address region check";

/// What a region check made of a host log and region table.
#[derive(Clone, Debug)]
pub struct RegionCheck {
    /// The profile text with the keys and the stamp.
    pub text: String,
    /// The findings: `(red, text)`.
    pub found: Vec<(bool, String)>,
}

/// The part of `region_check` after the boot. `rows` is the host's region table (empty when none), `sdk_syms` the
/// sdk's defined symbols, `log` the host log, `rc` the exit code when the host stopped by itself.
#[allow(clippy::too_many_arguments)]
pub fn region_check_result(
    text: &str,
    log: &str,
    rows: &str,
    sdk_syms: &[(String, (u64, u64))],
    rc: Option<i32>,
    secs: u32,
    rewrite: &str,
    date: &str,
) -> Result<RegionCheck, String> {
    let mut text = text.to_string();
    let depth = depth_signal(log, &keys_of(&text));
    if !depth.is_empty() {
        text = set_keys(&text, &signals_to_changes(&depth), "Address region check");
    }
    let g = keys_of(&text);
    let alias = super::pyfmt::int0(g.get("mem_alias").ok_or("the profile has no mem_alias")?)?;
    let lines: Vec<&str> = super::pyfmt::splitlines(&text);
    let checked = lines.iter().enumerate().any(|(i, l)| {
        l.starts_with("stdalloc_cap\t")
            && i > 0
            && lines[i - 1].starts_with(&format!("# {CHECKED_CAP}"))
    });
    let cap_of = |g: &Keys| {
        g.get("stdalloc_cap")
            .map_or(Ok(0), |v| super::pyfmt::int0(v))
    };
    let mut have = if checked { 0 } else { cap_of(&g)? };
    if have == 0 && !rows.is_empty() {
        let need = stdalloc_cap_needed(&region_rows(rows, sdk_syms)?, alias);
        let cur = cap_of(&g)?;
        if need != (cur != 0).then_some(cur) {
            let ch = (
                "stdalloc_cap".to_string(),
                need.map(|n| (format!("{n:#x}"), format!("{CHECKED_CAP}: the regions made after the StandardAllocator region need more room than the 256 MB the host leaves them"))),
            );
            text = set_keys(&text, &[ch], "Address region check");
        }
        have = need.unwrap_or(0);
    }
    let found = region_findings(rows, alias, sdk_syms, secs, have)?;
    let how = if rows.is_empty() {
        if rc.is_none() || log.contains(">>> nnMain") {
            "no region table (the sdk has no region gates)".to_string()
        } else {
            format!("the host stopped before nnMain (exit {})", rc.unwrap_or(0))
        }
    } else if found.is_empty() {
        "no address regions".to_string()
    } else {
        found[found.len() - 1].1.clone()
    };
    let old: Vec<&str> = text
        .trim_end_matches('\n')
        .split('\n')
        .filter(|l| !l.starts_with("# address regions: "))
        .collect();
    let out = format!(
        "{}\n\n# address regions: {date}, {how} (rewrite {rewrite})\n",
        old.join("\n").trim_end_matches('\n')
    );
    Ok(RegionCheck { text: out, found })
}

/// A step of the NSP script that boots the game on the Mac. Nothing here runs it: the build runs the reference
/// script for it (exit code 4, unsupported by contract) or skips it as `--no-heap-check` does.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RunNeeded {
    /// The step (`heap check`, `region check`, `capture`).
    pub step: &'static str,
    /// Why the game needs it.
    pub why: String,
}

/// The runs of the game a provisional profile for this survey needs: the heap check (virtual address memory and a
/// heap, unless `no_heap_check` or the profile is stamped), the address region check (virtual address memory, unless
/// `no_heap_check` or stamped for this rewrite) and the shader captures (`shader_sources`). With the RomFS `rom`, the
/// captures follow from its files and the modules of the profile in `stamps` (`build_sources`). Without it, they follow
/// from the survey's markers.
pub fn runs_needed(
    s: &Survey,
    exefs: &Path,
    no_heap_check: bool,
    stamps: Option<&str>,
    rewrite: &str,
    rom: Option<&super::rom::Rom>,
) -> Result<Vec<RunNeeded>, String> {
    let mut v = Vec::new();
    let text = stamps.unwrap_or("");
    if !no_heap_check && !heap_checked(text) && heap_check_needed(exefs)? {
        v.push(RunNeeded {
            step: "heap check",
            why:
                "virtual address memory and a heap: the heap request decides the alias / heap split"
                    .into(),
        });
    }
    if !no_heap_check && has_va(exefs)? && !region_checked(text, rewrite) {
        v.push(RunNeeded {
            step: "region check",
            why: "virtual address memory: where the game's address regions reach".into(),
        });
    }
    let keep: Vec<String> = s
        .guess
        .value("modules")
        .unwrap_or("")
        .split_whitespace()
        .map(str::to_string)
        .collect();
    let nro_dir = exefs.parent().map(|p| p.join("romfs_nro"));
    let inp = match rom {
        Some(r) => {
            let mut mods = TsvFile::parse(text).words("modules");
            if mods.is_empty() {
                mods.push("main".into());
            }
            mods.retain(|m| {
                exefs.join(m).is_file() || exefs.join(format!("{m}.patched.bin")).is_file()
            });
            super::build_sources::build_inputs(&s.facts, exefs, r, &mods)?
        }
        None => super::guess_src::survey_inputs(
            &s.facts,
            &keep,
            nro_dir.as_deref().filter(|d| d.is_dir()),
            &[],
        )?,
    };
    let src = super::guess_src::shader_sources(&inp);
    for (k, x) in [
        ("vk_capture", &src.vk_capture),
        ("gl_capture", &src.gl_capture),
        ("glslc_capture", &src.glslc_capture),
        ("ue_decode", &src.ue_decode),
        ("oodle_packs", &src.oodle_packs),
        ("ue_legacy", &src.ue_legacy),
    ] {
        if x.0 {
            v.push(RunNeeded {
                step: "capture",
                why: format!("{k}: {}", x.1),
            });
        }
    }
    Ok(v)
}
