//! `game.py header` for a multi-program application (`header_multi`): one host over the programs' profiles, every
//! program's constants in one table and `DM_GAME_*` macros that read the entry of the running program.

use super::header::{header_one, macros};
use super::profile::{Game, Profiles};

const ARR: [&str; 3] = [
    "DM_GAME_MODULES",
    "DM_GAME_BUILD_MODULES",
    "DM_GAME_DISPLAY_VERSIONS",
];

/// `re.findall(r'"(?:[^"\\]|\\.)*"', v)`.
fn strs(v: &str) -> Vec<&str> {
    let b = v.as_bytes();
    let mut out = vec![];
    let mut i = 0;
    while i < b.len() {
        if b[i] != b'"' {
            i += 1;
            continue;
        }
        let mut j = i + 1;
        let mut end = None;
        while j < b.len() {
            match b[j] {
                b'"' => {
                    end = Some(j);
                    break;
                }
                b'\\' if j + 1 < b.len() && b[j + 1] != b'\n' => j += 2,
                b'\\' => break,
                _ => j += 1,
            }
        }
        match end {
            Some(e) => {
                out.push(&v[i..=e]);
                i = e + 1;
            }
            None => i += 1,
        }
    }
    out
}

fn typ(v: &str) -> &'static str {
    if v.starts_with('"') {
        "const char *"
    } else if v.ends_with("ull") {
        "uint64_t "
    } else {
        "int "
    }
}

fn fld(k: &str) -> String {
    k["DM_GAME_".len()..].to_lowercase()
}

/// `game.header(g)`: one profile's header, or the table of its programs' (key `programs`).
pub fn header(g: &Game, p: &Profiles) -> Result<String, String> {
    if g.get_or("programs", "").is_empty() {
        return header_one(g, &p.here);
    }
    let mut progs = vec![(0i64, g.id.clone(), macros(&header_one(g, &p.here)?))];
    for w in g.words("programs")? {
        let (n, id) = w
            .split_once('=')
            .ok_or_else(|| "programs: not <index>=<profile>".to_string())?;
        let n: i64 = n
            .trim()
            .parse()
            .map_err(|_| format!("programs: bad index {n}"))?;
        let pg = p.load(id)?;
        progs.push((n, pg.id.clone(), macros(&header_one(&pg, &p.here)?)));
    }
    header_multi(&progs)
}

type Row = (i64, String, Vec<(String, String)>);

fn get<'a>(d: &'a [(String, String)], k: &str) -> Option<&'a str> {
    d.iter().find(|(x, _)| x == k).map(|(_, v)| v.as_str())
}

/// `game.header_multi(progs)` for the programs' ids and macros, program 0 first.
pub fn header_multi(rows: &[Row]) -> Result<String, String> {
    let mut keys: Vec<&str> = vec![];
    for (_, _, d) in rows {
        for (k, _) in d {
            if !keys.contains(&k.as_str()) {
                keys.push(k);
            }
        }
    }
    for k in [
        "DM_GAME_SHARED_FONT_TTF",
        "DM_GAME_NVN_API_MAJOR",
        "DM_GAME_NVN_API_MINOR",
    ] {
        if keys.contains(&k) {
            return Err(format!(
                "{k}: a key behind this macro (shared_font, device_api) is tested by the preprocessor and cannot differ per program; not supported with programs"
            ));
        }
    }
    let sz = |k: &str| {
        rows.iter()
            .map(|(_, _, d)| strs(get(d, k).unwrap_or("")).len())
            .max()
            .unwrap_or(0)
    };
    let scalars: Vec<&str> = keys.iter().copied().filter(|k| !ARR.contains(k)).collect();
    for k in &scalars {
        let mut ts: Vec<&str> = rows
            .iter()
            .filter_map(|(_, _, d)| get(d, k))
            .map(typ)
            .collect();
        ts.dedup();
        ts.sort_unstable();
        ts.dedup();
        if ts.len() > 1 {
            return Err(format!("{k}: different types among the programs"));
        }
    }
    let first = |k: &str| rows.iter().find_map(|(_, _, d)| get(d, k)).unwrap_or("");
    let ids: Vec<String> = rows.iter().map(|(n, g, _)| format!("{n} ({g})")).collect();
    let mut l: Vec<String> = vec![
        format!(
            "// Generated by dm/games/game.py from the profiles of programs {}; do not edit",
            ids.join(", ")
        ),
        "#pragma once".into(),
        "#include <stdint.h>".into(),
        "#include <stddef.h>".into(),
        "#define DM_GAME_MULTI 1".into(),
    ];
    let sc: Vec<String> = scalars
        .iter()
        .map(|k| format!("{}{};", typ(first(k)), fld(k)))
        .collect();
    let ar: Vec<String> = ARR
        .iter()
        .map(|k| format!("const char *{}[{}];", fld(k), sz(k).max(1)))
        .collect();
    l.push(format!(
        "typedef struct {{ int program; {} {} }} dm_game_t;",
        sc.join(" "),
        ar.join(" ")
    ));
    l.push("static const dm_game_t dm_games[] __attribute__((unused)) = {".into());
    for (n, _, d) in rows {
        let s: Vec<String> = scalars
            .iter()
            .filter_map(|k| get(d, k).map(|v| format!(".{} = {v}", fld(k))))
            .collect();
        let a: Vec<String> = ARR
            .iter()
            .map(|k| {
                format!(
                    ".{} = {{{}}}",
                    fld(k),
                    strs(get(d, k).unwrap_or("")).join(", ")
                )
            })
            .collect();
        l.push(format!(
            "    {{.program = {n}, {}, {}}},",
            s.join(", "),
            a.join(", ")
        ));
    }
    l.push("};".into());
    l.push("const dm_game_t *dm_game_cur(void);   // main.c: the entry of the program DM_PROGRAM names".into());
    for k in &scalars {
        l.push(format!("#define {k} (dm_game_cur()->{})", fld(k)));
    }
    for k in ARR {
        let e: Vec<String> = (0..sz(k))
            .map(|i| format!("dm_game_cur()->{}[{i}]", fld(k)))
            .collect();
        l.push(format!("#define {k} {{{}}}", e.join(", ")));
    }
    l.push(String::new());
    Ok(l.join("\n"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn string_lists() {
        assert_eq!(strs(r#"{"a", "b\"c"}"#), ["\"a\"", "\"b\\\"c\""]);
        assert!(strs("{").is_empty());
    }

    /// Oracle: `NXB_ORACLE_ENGINE` and `NXB_ORACLE_PYTHON`. `game.py header` of every profile that the engine lists,
    /// against [`header`] (the profiles with `programs` give the table of their programs).
    #[test]
    fn every_header_equals_the_reference_script() {
        let (Some(e), Some(py)) = (
            std::env::var_os("NXB_ORACLE_ENGINE"),
            std::env::var_os("NXB_ORACLE_PYTHON"),
        ) else {
            return;
        };
        let game_py = std::path::Path::new(&e).join("dm/games/game.py");
        let list = std::process::Command::new(&py)
            .arg(&game_py)
            .arg("list")
            .output()
            .unwrap();
        let p = Profiles::new(std::path::Path::new(&e), &|_| None);
        let out = std::env::temp_dir().join(format!("nxb-header-all-{}.h", std::process::id()));
        let mut n = 0;
        for id in String::from_utf8_lossy(&list.stdout)
            .lines()
            .filter_map(|l| l.split('\t').next())
        {
            let _ = std::fs::remove_file(&out);
            let st = std::process::Command::new(&py)
                .arg(&game_py)
                .args(["header", id])
                .arg(&out)
                .output()
                .unwrap();
            let got = header(&p.load(id).unwrap(), &p);
            if !st.status.success() {
                assert!(got.is_err(), "{id}: the reference refused the header");
                continue;
            }
            assert_eq!(got.unwrap(), std::fs::read_to_string(&out).unwrap(), "{id}");
            n += 1;
        }
        let _ = std::fs::remove_file(&out);
        eprintln!("{n} headers identical");
        assert!(n > 100);
    }

    /// Oracle: `NXB_ORACLE_ENGINE`, `NXB_ORACLE_PYTHON`, `NXB_ORACLE_MULTI` (a profile with `programs`): `game.py header`
    /// of it against [`header`].
    #[test]
    fn multi_program_header_equals_the_reference_script() {
        let (Some(e), Some(py), Some(id)) = (
            std::env::var_os("NXB_ORACLE_ENGINE"),
            std::env::var_os("NXB_ORACLE_PYTHON"),
            std::env::var("NXB_ORACLE_MULTI").ok(),
        ) else {
            return;
        };
        let out = std::env::temp_dir().join(format!("nxb-header-multi-{}.h", std::process::id()));
        let st = std::process::Command::new(py)
            .arg(std::path::Path::new(&e).join("dm/games/game.py"))
            .args(["header", &id])
            .arg(&out)
            .status()
            .unwrap();
        assert!(st.success());
        let p = Profiles::new(std::path::Path::new(&e), &|_| None);
        let got = header(&p.load(&id).unwrap(), &p).unwrap();
        let want = std::fs::read_to_string(&out).unwrap();
        let _ = std::fs::remove_file(&out);
        assert!(got.contains("DM_GAME_MULTI"));
        assert_eq!(got, want);
    }
}
