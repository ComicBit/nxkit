//! `dm/ios/tools/gen_resources.py`: after `xcodegen`, the game's resource paths for the Xcode build phase
//! (`Gen/resources.env`, one `KEY=shlex.quote(value)` line each), the derived data root appended to `Gen/dm.xcconfig`,
//! and the per-user workspace settings (`WorkspaceSettings.xcsettings`, `plistlib.dumps`) that keep Xcode's derived
//! data on the game's drive. No game files are copied.

use super::{resolve, shlex_quote};
use nxb_pack::plist::{Value as Plist, parse};
use nxb_pack::pyplist::{PyValue, dumps};
use std::io::Write;
use std::path::Path;

/// The script's arguments and the environment it reads (`GAME`, `DM_APP_VERSION`, `DM_RESOURCE_BUILD`, `USER`).
#[derive(Clone, Debug, Default)]
pub struct Inputs {
    /// The iOS project folder (`Gen/` and `DmIOS.xcodeproj` in it).
    pub ios: String,
    /// The RomFS folder or image.
    pub romfs: String,
    /// The profile's `romfs_marker`.
    pub marker: String,
    /// The shader library folder.
    pub shaders: String,
    /// Its folder name in the app (`b-<chain>`, `vk`, `gl`).
    pub msldir: String,
    /// The add-on content folder (empty: none).
    pub aoc: String,
    /// Xcode's derived data.
    pub derived: String,
    /// `dm/gfx/nvn/dmsh_chain.h`.
    pub chain_h: String,
    /// The offline pipeline archive (empty: none).
    pub pso: String,
    /// A game of several programs: the table of their files, relative to `ios` (`Gen/resources_programs.tsv`).
    pub programs: Option<String>,
    /// `GAME`.
    pub title: String,
    /// `DM_APP_VERSION`.
    pub version: String,
    /// `DM_RESOURCE_BUILD`.
    pub build: String,
    /// `USER` (or `getpass.getuser()`).
    pub user: String,
}

fn is_dir(p: &str) -> bool {
    !p.is_empty() && Path::new(p).is_dir()
}

/// The text of `Gen/resources.env`.
pub fn resources_env(i: &Inputs) -> Result<String, String> {
    let opt = |p: &str| -> Result<String, String> {
        if is_dir(p) {
            resolve(p)
        } else {
            Ok(String::new())
        }
    };
    let programs = match &i.programs {
        Some(p) => resolve(&format!("{}/{p}", i.ios))?,
        None => String::new(),
    };
    let pairs = [
        ("DM_RESOURCE_ROMFS", resolve(&i.romfs)?),
        ("DM_RESOURCE_MARKER", i.marker.clone()),
        ("DM_RESOURCE_SHADERS", resolve(&i.shaders)?),
        ("DM_RESOURCE_MSLDIR", i.msldir.clone()),
        ("DM_RESOURCE_AOC", opt(&i.aoc)?),
        ("DM_RESOURCE_CHAIN_H", resolve(&i.chain_h)?),
        ("DM_RESOURCE_PSO", opt(&i.pso)?),
        ("DM_RESOURCE_TITLE", i.title.clone()),
        ("DM_RESOURCE_VERSION", i.version.clone()),
        ("DM_RESOURCE_BUILD", i.build.clone()),
        ("DM_RESOURCE_PROGRAMS", programs),
    ];
    let mut s = String::from(
        "# Generated by build_ipa.sh; regenerate when the game or its drive changes.\n",
    );
    for (k, v) in pairs {
        s.push_str(&format!("{k}={}\n", shlex_quote(&v)));
    }
    Ok(s)
}

fn py_value(v: &Plist) -> Result<PyValue, String> {
    Ok(match v {
        Plist::Dict(d) => PyValue::Dict(
            d.iter()
                .map(|(k, v)| Ok((k.clone(), py_value(v)?)))
                .collect::<Result<_, String>>()?,
        ),
        Plist::Array(a) => PyValue::List(a.iter().map(py_value).collect::<Result<_, _>>()?),
        Plist::String(s) => PyValue::Str(s.clone()),
        Plist::Integer(i) => PyValue::Int(*i),
        Plist::Real(f) => PyValue::Real(*f),
        Plist::Bool(b) => PyValue::Bool(*b),
        Plist::Data(_) | Plist::Date(_) => {
            return Err("workspace settings: a <data> or <date> value is not kept here".into());
        }
    })
}

/// `workspace_settings(workspace, derived)`: the existing `WorkspaceSettings.xcsettings` with the derived data at
/// `derived` and the custom build locations removed, other keys are kept (the file is written sorted, as `plistlib`).
pub fn workspace_settings(workspace: &Path, derived: &str, user: &str) -> Result<(), String> {
    let path = workspace
        .join("xcuserdata")
        .join(format!("{user}.xcuserdatad"))
        .join("WorkspaceSettings.xcsettings");
    let mut values: Vec<(String, PyValue)> = if path.exists() {
        let b = std::fs::read(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        match py_value(&parse(&b).map_err(|e| format!("{}: {e}", path.display()))?)? {
            PyValue::Dict(d) => d,
            _ => return Err(format!("{}: not a dictionary", path.display())),
        }
    } else {
        Vec::new()
    };
    let derived = resolve(derived)?;
    for (k, v) in [
        ("BuildLocationStyle", "UseAppPreferences"),
        ("DerivedDataLocationStyle", "AbsolutePath"),
        ("DerivedDataCustomLocation", derived.as_str()),
    ] {
        crate::host::profile::dict_set(&mut values, k, PyValue::Str(v.into()));
    }
    values.retain(|(k, _)| {
        ![
            "CustomBuildLocationType",
            "CustomBuildProductsPath",
            "CustomBuildIntermediatesPath",
        ]
        .contains(&k.as_str())
    });
    if let Some(p) = path.parent() {
        std::fs::create_dir_all(p).map_err(|e| format!("{}: {e}", p.display()))?;
    }
    std::fs::write(&path, dumps(&PyValue::Dict(values)))
        .map_err(|e| format!("{}: {e}", path.display()))
}

/// `main()`: `Gen/resources.env`, the `DM_XCODE_OUTPUT_ROOT` line of `Gen/dm.xcconfig` and the workspace settings of
/// `DmIOS.xcodeproj/project.xcworkspace`.
pub fn write(i: &Inputs) -> Result<(), String> {
    let ios = Path::new(&i.ios);
    let env = ios.join("Gen/resources.env");
    std::fs::write(&env, resources_env(i)?).map_err(|e| format!("{}: {e}", env.display()))?;
    let cfg = ios.join("Gen/dm.xcconfig");
    let line = format!("DM_XCODE_OUTPUT_ROOT = {}\n", resolve(&i.derived)?);
    std::fs::OpenOptions::new()
        .append(true)
        .create(true)
        .open(&cfg)
        .and_then(|mut f| f.write_all(line.as_bytes()))
        .map_err(|e| format!("{}: {e}", cfg.display()))?;
    workspace_settings(
        &ios.join("DmIOS.xcodeproj/project.xcworkspace"),
        &i.derived,
        &i.user,
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ios::oracle;

    /// An iOS folder with `Gen/dm.xcconfig`, an existing settings file with a custom build location, resources that
    /// exist (RomFS through a symlink, AOC, PSO) and a programs table.
    fn fixture(d: &Path) -> Inputs {
        let ios = d.join("ios");
        std::fs::create_dir_all(ios.join("Gen")).unwrap();
        std::fs::write(ios.join("Gen/dm.xcconfig"), "A = 1\n").unwrap();
        let ws = ios.join("DmIOS.xcodeproj/project.xcworkspace/xcuserdata/tester.xcuserdatad");
        std::fs::create_dir_all(&ws).unwrap();
        std::fs::write(
            ws.join("WorkspaceSettings.xcsettings"),
            "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<plist version=\"1.0\">\n<dict>\n\t<key>CustomBuildLocationType</key>\n\t<string>RelativeToDerivedData</string>\n\t<key>Zed</key>\n\t<true/>\n\t<key>Count</key>\n\t<integer>3</integer>\n</dict>\n</plist>\n",
        )
        .unwrap();
        for f in ["data/RomFS", "aoc", "pso", "msl/b-1"] {
            std::fs::create_dir_all(d.join(f)).unwrap();
        }
        std::os::unix::fs::symlink(d.join("data"), d.join("link")).unwrap();
        let s = |p: &str| d.join(p).to_str().unwrap().to_string();
        Inputs {
            ios: s("ios"),
            romfs: s("link/RomFS"),
            marker: "Data/it's here".into(),
            shaders: s("msl/b-1/../b-1"),
            msldir: "b-1".into(),
            aoc: s("aoc"),
            derived: s("dd/new"),
            chain_h: s("chain.h"),
            pso: s("pso"),
            programs: Some("Gen/resources_programs.tsv".into()),
            title: "0100000000001000".into(),
            version: "1.0 \"beta\"".into(),
            build: "v65536".into(),
            user: "tester".into(),
        }
    }

    #[test]
    fn writes_the_three_files() {
        let d = oracle::scratch("res");
        let i = fixture(&d);
        write(&i).unwrap();
        let env = std::fs::read_to_string(d.join("ios/Gen/resources.env")).unwrap();
        assert!(env.contains("DM_RESOURCE_MARKER='Data/it'\"'\"'s here'\n"));
        assert!(env.contains("DM_RESOURCE_VERSION='1.0 \"beta\"'\n"));
        assert!(env.contains("/data/RomFS\n"));
        let s = std::fs::read_to_string(d.join("ios/DmIOS.xcodeproj/project.xcworkspace/xcuserdata/tester.xcuserdatad/WorkspaceSettings.xcsettings")).unwrap();
        assert!(s.contains("<key>BuildLocationStyle</key>\n\t<string>UseAppPreferences</string>\n\t<key>Count</key>\n\t<integer>3</integer>\n"));
        assert!(!s.contains("CustomBuildLocationType"));
        let _ = std::fs::remove_dir_all(&d);
    }

    /// Oracle: the engine's `gen_resources.py` on the same fixture (two copies), all three files byte for byte.
    #[test]
    fn equals_the_reference_script() {
        let Some(e) = oracle::engine() else { return };
        for (n, empty) in [(0, false), (1, true)] {
            let (pd, rd) = (
                oracle::scratch(&format!("res-py{n}")),
                oracle::scratch(&format!("res-rs{n}")),
            );
            let mut pi = fixture(&pd);
            let mut ri = fixture(&rd);
            if empty {
                for i in [&mut pi, &mut ri] {
                    i.aoc = String::new();
                    i.pso = String::new();
                    i.programs = None;
                }
            }
            let mut c = oracle::python();
            c.arg(e.join("dm/ios/tools/gen_resources.py")).args([
                &pi.ios,
                &pi.romfs,
                &pi.marker,
                &pi.shaders,
                &pi.msldir,
                &pi.aoc,
                &pi.derived,
                &pi.chain_h,
            ]);
            if !empty {
                c.args([&pi.pso, pi.programs.as_ref().unwrap()]);
            }
            c.env("GAME", &pi.title)
                .env("DM_APP_VERSION", &pi.version)
                .env("DM_RESOURCE_BUILD", &pi.build)
                .env("USER", &pi.user);
            assert!(c.status().unwrap().success());
            write(&ri).unwrap();
            let rel = |root: &Path, f: &str| {
                let real = std::fs::canonicalize(root).unwrap();
                std::fs::read_to_string(root.join(f))
                    .unwrap()
                    .replace(real.to_str().unwrap(), "<root>")
                    .replace(root.to_str().unwrap(), "<root>")
            };
            for f in [
                "ios/Gen/resources.env",
                "ios/Gen/dm.xcconfig",
                "ios/DmIOS.xcodeproj/project.xcworkspace/xcuserdata/tester.xcuserdatad/WorkspaceSettings.xcsettings",
            ] {
                assert_eq!(rel(&rd, f), rel(&pd, f), "{f}");
            }
            let _ = std::fs::remove_dir_all(&pd);
            let _ = std::fs::remove_dir_all(&rd);
        }
    }
}
