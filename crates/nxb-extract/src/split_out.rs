//! The split's output files: package files, `shader_map.tsv`, the compute answer table and the two pair tables
//! (the end of `main()` of `shader_split.py`).

use nxb_split::records::Outputs;

use crate::error::{ExtractError, Result};
use crate::split::{SplitOutputs, split_err, write};

/// `{n:,}` of the Python.
fn thousands(n: usize) -> String {
    let s = n.to_string();
    let mut o = String::new();
    for (i, c) in s.chars().enumerate() {
        if i > 0 && (s.len() - i).is_multiple_of(3) {
            o.push(',');
        }
        o.push(c);
    }
    o
}

pub(crate) fn write_outputs(
    req: &SplitOutputs,
    game_tsv: &str,
    manual: Option<&str>,
    out: &Outputs,
    bad: usize,
) -> Result<()> {
    let mut facts = out.facts.clone();
    if let Some(m) = manual {
        crate::facts::merge_manual(&mut facts, m).map_err(ExtractError::Format)?;
    }
    std::fs::create_dir_all(&req.pkg)
        .map_err(|e| ExtractError::io(format!("create {}", req.pkg.display()), e))?;
    if let Ok(rd) = std::fs::read_dir(&req.pkg) {
        for e in rd.flatten() {
            if e.file_name().to_string_lossy().ends_with(".bin") {
                let _ = std::fs::remove_file(e.path());
            }
        }
    }
    for (name, bytes) in &out.packages {
        write(&req.pkg.join(name), bytes)?;
    }
    let note = game_tsv
        .lines()
        .find_map(|l| l.strip_prefix("shader_note\t"))
        .unwrap_or("None");
    // the kinds of sources that appear, in the Python's order
    let has = |f: &dyn Fn(&str) -> bool| out.rows.iter().any(|r| f(&r.4));
    let kinds = [
        (
            "BNSH / BAHS",
            has(&|p| p.contains("#BNSH@") || p.contains("#BAHS@")),
        ),
        ("MSHD", has(&|p| p.contains("#MSHD#"))),
        ("GLSLC", has(&|p| p.contains("#GLSLC@"))),
        (
            "PlatinumGames shader objects",
            has(&|p| p.contains("#PGSO")),
        ),
    ]
    .iter()
    .filter(|k| k.1)
    .map(|k| k.0)
    .collect::<Vec<_>>()
    .join(" / ");
    let mut m = format!(
        "# kind: evidence  {note} ({kinds} in RomFS + main) \u{2192} control section + code area keys (dm/gfx/tools/shader_split.py)\n# column 5 records where each key first appears; no PC shader pairing supplied\npackage\tindex\tstage\tdm_ctl_sha16\tsource\n"
    );
    for r in &out.rows {
        m.push_str(&format!("{}\t{}\t{}\t{}\t{}\n", r.0, r.1, r.2, r.3, r.4));
    }
    write(&req.map, m.as_bytes())?;
    let mut f = String::from(
        "# Answer table for translation queries (generated by dm/gfx/tools/shader_split.py, do not edit): key <TAB> fact JSON. No PC shader pairing supplied: only the thread group / shared memory of compute shaders (taken from the control section); other queries get the translator defaults\n",
    );
    for (k, v) in &facts {
        f.push_str(&format!("{k}\t{v}\n"));
    }
    write(&req.facts, f.as_bytes())?;
    let mut p = String::from(
        "# kind: evidence  vertex / pixel shader pairs within BNSH variations (generated by dm/gfx/tools/shader_split.py, do not edit): vertex key <TAB> pixel key\n",
    );
    for (a, b) in &out.pairs {
        p.push_str(&format!("{a}\t{b}\n"));
    }
    write(&req.pairs, p.as_bytes())?;
    let mut q = String::from(
        "# kind: evidence  supplemental vertex / pixel shader pairs (BAHS program variations and legacy Unity pass-input covers) for vertex output padding and the pipeline prebuild (generated by dm/gfx/tools/shader_split.py, do not edit): vertex key <TAB> pixel key\n",
    );
    for (a, b) in &out.pso_pairs {
        q.push_str(&format!("{a}\t{b}\n"));
    }
    write(&req.pso_pairs, q.as_bytes())?;
    if bad > 0 {
        println!("[RED] {bad} file(s) could not be read, their shaders are left out");
    }
    if let Some((n, cover)) = &out.single {
        println!(
            "single-stage programs: {} vertex shaders are paired with a cover of {} pixel shader(s) ({})",
            thousands(*n),
            cover.len(),
            cover.join(" ")
        );
    }
    let (stat, src) = &out.stats;
    let stages: Vec<String> = stat
        .iter()
        .map(|(s, n)| format!("{} {n}", stage_long(s)))
        .collect();
    let sources: Vec<String> = src.iter().map(|(g, n)| format!("{g} {n}")).collect();
    println!(
        "shaders: {} ({}); sources {}; compute shader answers {} rows; variation pairs {}",
        out.rows.len(),
        stages.join(", "),
        sources.join(", "),
        facts.len(),
        out.pairs.len()
    );
    Ok(())
}

fn stage_long(s: &str) -> &'static str {
    match s {
        "vs" => "vertex",
        "ps" => "pixel",
        "cs" => "compute",
        "gs" => "geometry",
        "hs" => "hull",
        "ds" => "domain",
        "ts" => "task",
        "ms" => "mesh",
        _ => "?",
    }
}

/// The files of `dir` ending in `ext`, sorted, AppleDouble files (`._*`) left out.
fn named(dir: &std::path::Path, ext: &str) -> Vec<String> {
    let mut v: Vec<String> = std::fs::read_dir(dir)
        .map(|rd| {
            rd.flatten()
                .filter_map(|e| e.file_name().into_string().ok())
                .filter(|n| n.ends_with(ext) && !n.starts_with("._"))
                .collect()
        })
        .unwrap_or_default();
    v.sort();
    v
}

/// What the build's boots wrote beside a version's image, scanned after main: the GLSLC outputs the game compiled at
/// run time (`<dir>/glslc_capture` or `DM_GLSLC_CAPTURE`, labels `/glslc_capture/<name>`) and the Unreal shader code
/// archives decoded with the game's Oodle (`<dir>/ue_shaders` or `DM_UE_SHADERS`, labels `/ue_shaders/<name>`).
pub(crate) fn host_made(dir: &std::path::Path) -> Result<Vec<nxb_split::shaders::Found>> {
    let env = |k: &str, d: &str| {
        std::env::var_os(k)
            .filter(|v| !v.is_empty())
            .map_or_else(|| dir.join(d), std::path::PathBuf::from)
    };
    let read = |p: &std::path::Path| {
        std::fs::read(p).map_err(|e| ExtractError::io(format!("read {}", p.display()), e))
    };
    let mut found = Vec::new();
    let cap = env("DM_GLSLC_CAPTURE", "glslc_capture");
    for n in named(&cap, ".glslc") {
        let d = read(&cap.join(&n))?;
        found.extend(
            nxb_split::glslc::glslc_shaders(&d, &format!("/glslc_capture/{n}"), true, &[])
                .map_err(split_err)?,
        );
    }
    let ued = env("DM_UE_SHADERS", "ue_shaders");
    for n in named(&ued, ".ushaderbytecode") {
        let d = read(&ued.join(&n))?;
        found.extend(
            nxb_split::jobs::ue_shaders(&d, &format!("/ue_shaders/{n}")).map_err(split_err)?,
        );
    }
    Ok(found)
}

/// The NROs of `DM_NRO_DIR` (`*.nro`, hidden files left out, sorted by name): the file table of a CRA archive is in
/// one of them, and every NRO is scanned like main's image.
#[derive(Default)]
pub(crate) struct Nros {
    /// The variable's text, `None` when it is unset (the reference names it in a message).
    pub dir: String,
    /// File name and bytes.
    pub files: Vec<(String, std::sync::Arc<Vec<u8>>)>,
}

pub(crate) fn read_nros(given: Option<&std::path::Path>) -> Result<Nros> {
    let Some(dir) = given
        .map(|d| d.as_os_str().to_os_string())
        .or_else(|| std::env::var_os("DM_NRO_DIR"))
    else {
        return Ok(Nros {
            dir: "None".into(),
            files: Vec::new(),
        });
    };
    let path = std::path::Path::new(&dir);
    let mut names: Vec<String> = std::fs::read_dir(path)
        .map(|rd| {
            rd.flatten()
                .filter(|e| e.path().is_file())
                .filter_map(|e| e.file_name().into_string().ok())
                .filter(|n| n.ends_with(".nro") && !n.starts_with('.'))
                .collect()
        })
        .unwrap_or_default();
    names.sort();
    let mut files = Vec::new();
    for n in names {
        let p = path.join(&n);
        let d =
            std::fs::read(&p).map_err(|e| ExtractError::io(format!("read {}", p.display()), e))?;
        files.push((n, std::sync::Arc::new(d)));
    }
    Ok(Nros {
        dir: dir.to_string_lossy().into_owned(),
        files,
    })
}
