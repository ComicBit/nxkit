/// Refills `l` from the header bytes read backward (`for (l = ...; rawDataSize; l = ip[rawDataSize--] | l << 8)`).
fn refill(mut l: u64, ip: &[u8], raw: &mut usize) -> u64 {
    while *raw != 0 && (l >> 32) & 0xFFFF_FFFF < 0x100 {
        l = u64::from(ip[*raw]) | (l << 8);
        *raw -= 1;
    }
    l
}

/// `FSE_readNCount_bic`: the normalized counters, the accuracy log and the bytes used.
pub(super) fn read_ncount(ip: &[u8], max_sym: usize) -> R<(Vec<i16>, u32, usize)> {
    let first = *ip.first().ok_or_else(|| err("empty table description"))?;
    let mut raw = usize::from(first & 0x7F);
    let low_prob = u32::from(first >> 7);
    if raw >= ip.len() || raw + 1 >= ip.len() {
        return Err(err("table description past the end"));
    }
    let data_size = raw + 1;
    let i = refill(0, ip, &mut raw);
    let mut enc = i / 0x34;
    let j = (i % 0x34) as u32;
    enc = refill(enc, ip, &mut raw);
    let char_num = j + 1;
    if char_num as usize > max_sym {
        return Err(err("table has too many symbols"));
    }
    let mut char_table = enc >> 3;
    let k = (enc & 7) as u32;
    char_table = refill(char_table, ip, &mut raw);
    let table_log = k + 5;
    let mut remaining: u32 = 1 << table_log;
    let mut l = char_table / u64::from(remaining);
    l = refill(l, ip, &mut raw);
    let mut char_last = (char_table % u64::from(remaining)) as u32 + 1;
    if low_prob != 0 {
        char_last = char_num + (char_table % u64::from(remaining)) as u32 + 2;
    }
    // the next power of two strictly above char_num
    let pow2 = 1u32 << (32 - char_num.leading_zeros());
    if pow2 > 0xFF {
        return Err(err("table has too many symbols"));
    }
    let mut counter = [0u32; 257];
    counter[pow2 as usize] = char_last;
    for n in 0..pow2 {
        let o = 3 * (0x100 - pow2 + n) as usize;
        let (mid, lo, hi) = (
            usize::from(BIC[o]),
            usize::from(BIC[o + 1]),
            usize::from(BIC[o + 2]),
        );
        let (a, b) = (counter[lo], counter[hi]);
        if a == b {
            for c in counter.iter_mut().take(hi).skip(lo + 1) {
                *c = a;
            }
        } else {
            let span = u64::from(b.wrapping_sub(a).wrapping_add(1));
            if span == 0 {
                return Err(err("table description"));
            }
            let entry = l % span;
            l = refill(l / span, ip, &mut raw);
            counter[mid] = entry as u32 + a;
        }
    }
    let mut norm = Vec::with_capacity(char_num as usize + 1);
    let mut acc: i32 = 0;
    for c in counter.iter().skip(1).take(char_num as usize + 1) {
        let bc = *c as u16 as i16;
        let dist = bc.wrapping_sub(acc as i16);
        let count = dist.wrapping_sub(low_prob as i16);
        acc += i32::from(dist);
        norm.push(count);
        remaining = remaining.wrapping_sub(i32::from(count).unsigned_abs());
    }
    if remaining != 0 || raw != 0 {
        return Err(err("table description"));
    }
    Ok((norm, table_log, data_size))
}
